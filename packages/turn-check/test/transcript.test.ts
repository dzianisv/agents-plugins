import { describe, expect, test } from "bun:test"
import { JudgeError, replyFromEvents } from "../src/core/judge-cli"
import { auditorSystem, buildPrompt, formatError, formatFeedback, hasAgentWork, isViolationFeedback, MAX_PROMPT_CHARS, parseVerdict, renderTranscript, summariseTool, USER_MESSAGE_CAP, type Msg } from "../src/core/prompt"
import { buildMessages, lastEntryUuid } from "../src/core/transcript-claude"
import { assistant, text, toolResult, toolUse, user } from "./helpers"

const msg = (role: string, ...parts: any[]): Msg => ({ info: { id: "x", role }, parts })
const t = (value: string) => ({ type: "text", text: value })
const tl = (name: string, input: object, output = "") => ({ type: "tool", tool: name, input, output })

const PASS_REPLY = '{"verdict":"PASS","violations":[]}'

describe("Claude transcript", () => {
  test("renders user text, assistant text and tool lines", () => {
    const entries = [
      user("fix the bug"),
      assistant([text("on it"), toolUse("t1", "Bash", { command: "go test ./..." })], "a1"),
      toolResult("r1", "t1", "ok pkg 0.1s"),
      assistant([text("done")], "a2"),
    ]
    const out = renderTranscript(buildMessages(entries), 10000)
    expect(out).toContain("[#0 USER]\nfix the bug")
    expect(out).toContain("[#1 ASSISTANT]\non it\n  tool Bash: go test ./... -> ok pkg 0.1s")
    expect(out).toContain("[#2 ASSISTANT]\ndone")
  })

  test("assistant blocks with one api id are one message", () => {
    const entries = [
      user("hi"),
      assistant([text("part one")], "a1", "m1"),
      assistant([toolUse("t1", "Read", { file_path: "/a/b.go" })], "a2", "m1"),
    ]
    const msgs = buildMessages(entries)
    expect(msgs.map((m) => m.info.role)).toEqual(["user", "assistant"])
    expect(msgs[1].info.id).toBe("a2")
    expect(renderTranscript(msgs, 1000)).toContain("tool Read: /a/b.go")
  })

  test("skips tool results, meta, reminders, commands and sidechains", () => {
    const entries = [
      user("real ask", "u1"),
      user("meta text", "u2", { isMeta: true }),
      user("<system-reminder>x</system-reminder>", "u3"),
      user("<command-name>/clear</command-name>", "u4"),
      user("<local-command-stdout>ok</local-command-stdout>", "u5"),
      user("Caveat: generated by tools", "u6"),
      user("sidechain ask", "u7", { isSidechain: true }),
      user("summary of old chat", "u8", { isCompactSummary: true }),
      toolResult("r1", "unknown", "result"),
    ]
    expect(renderTranscript(buildMessages(entries), 10000)).toBe("[#0 USER]\nreal ask")
  })

  test("user blocks keep real text and drop reminder blocks", () => {
    const entry = user([text("<system-reminder>ctx</system-reminder>"), text("do the thing")])
    expect(renderTranscript(buildMessages([entry]), 1000)).toBe("[#0 USER]\ndo the thing")
  })

  test("tool line picks a known key else JSON, and clips", () => {
    expect(summariseTool(tl("Grep", { pattern: "foo", path: "." }))).toBe("  tool Grep: foo")
    expect(summariseTool(tl("X", { n: 1 }))).toBe('  tool X: {"n":1}')
    const line = summariseTool(tl("Bash", { command: "a ".repeat(300) }, "o".repeat(1000)))
    expect(line.length).toBeLessThan(520)
    expect(summariseTool(tl("Bash", { command: "a\n\nb" }, "x\n y"))).toBe("  tool Bash: a b -> x y")
  })

  test("tool result blocks as a list are joined", () => {
    const entries = [assistant([toolUse("t1", "Bash", { command: "ls" })]), toolResult("r1", "t1", [text("one"), text("two")])]
    expect(renderTranscript(buildMessages(entries), 1000)).toContain("-> one two")
  })

  test("over the limit keeps every user message and drops the oldest agent output", () => {
    const msgs = [msg("user", t("first ask")), msg("assistant", t("old ".repeat(900))), msg("user", t("second ask")), msg("assistant", t("new ".repeat(900)))]
    const out = renderTranscript(msgs, 4000)
    expect(out).toContain("first ask")
    expect(out).toContain("second ask")
    expect(out).toContain("[1 earlier agent message(s) omitted]")
    expect(out).toContain("new new")
    expect(out).not.toContain("old old")
  })

  test("agent output is one contiguous run ending at the newest", () => {
    const msgs = [msg("assistant", t("OLD")), msg("assistant", t("MIDDLE".repeat(400))), msg("assistant", t("NEW".repeat(200)))]
    const out = renderTranscript(msgs, 2500)
    expect(out).toContain("NEWNEW")
    expect(out).not.toContain("MIDDLE")
    expect(out).not.toContain("OLD")
    expect(out).toContain("[2 earlier agent message(s) omitted]")
  })

  test("the newest agent message is kept even when it alone exceeds the limit", () => {
    const out = renderTranscript([msg("user", t("ask")), msg("assistant", t("z".repeat(9000)))], 3000)
    expect(out).toContain("zzz")
  })

  test("user messages are capped at 2000 chars", () => {
    const out = renderTranscript([msg("user", t("u".repeat(5000)))], 100000)
    expect(out.length).toBeLessThan(2100)
    expect(out.endsWith("…")).toBe(true)
  })

  test("has agent work", () => {
    expect(hasAgentWork([msg("user", t("hi"))])).toBe(false)
    expect(hasAgentWork([msg("user", t("hi")), msg("assistant", t("hello"))])).toBe(true)
    expect(hasAgentWork([msg("user", t("hi")), msg("assistant", tl("Bash", {}))])).toBe(true)
    expect(hasAgentWork([msg("assistant", t("old")), msg("user", t("new"))])).toBe(false)
  })

  test("last entry uuid ignores sidechains and other types", () => {
    const entries = [user("a", "u1"), assistant([text("b")], "a1"), { type: "last-prompt", uuid: "zz" }, user("c", "u9", { isSidechain: true })]
    expect(lastEntryUuid(entries)).toBe("a1")
  })
})

describe("verdict parsing", () => {
  test("fenced JSON is parsed and capped at five", () => {
    const violations = Array.from({ length: 8 }, (_, i) => ({ rule: `rule ${i}`, evidence: "#1 q", fix: "do x" }))
    const verdict = parseVerdict("```json\n" + JSON.stringify({ verdict: "FAIL", violations }) + "\n```")
    expect(verdict?.verdict).toBe("FAIL")
    expect(verdict?.violations).toHaveLength(5)
  })

  test("PASS with no violations", () => {
    expect(parseVerdict(PASS_REPLY)).toEqual({ verdict: "PASS", violations: [] })
  })

  test("a FAIL without usable violations is rejected", () => {
    expect(parseVerdict('{"verdict":"FAIL","violations":[{"rule":" "}]}')).toBeNull()
    expect(parseVerdict('{"verdict":"FAIL"}')).toBeNull()
  })

  test("PASS ignores listed violations", () => {
    expect(parseVerdict('{"verdict":"PASS","violations":[{"rule":"x"}]}')).toEqual({ verdict: "PASS", violations: [] })
  })

  test("garbage and unknown verdicts are rejected", () => {
    for (const reply of ["I think it is fine", '{"verdict":"MAYBE"}', "{not json}", "", "[1,2]"]) {
      expect(parseVerdict(reply)).toBeNull()
    }
  })

  test("fields are clipped and missing ones default to empty", () => {
    const verdict = parseVerdict(JSON.stringify({ verdict: "FAIL", violations: [{ rule: "r".repeat(300), evidence: "e".repeat(400) }] }))
    const v = verdict!.violations[0]
    expect(v.rule.length).toBe(201)
    expect(v.evidence.length).toBe(301)
    expect(v.fix).toBe("")
  })

  test("prose around the JSON is tolerated", () => {
    expect(parseVerdict("Sure! " + PASS_REPLY + " Done.")).toEqual({ verdict: "PASS", violations: [] })
  })
})

describe("feedback text", () => {
  test("lists each violation with evidence and fix", () => {
    const out = formatFeedback([
      { rule: "Max 6 lines", evidence: "#4 12 lines", fix: "shorten" },
      { rule: "No emoji", evidence: "", fix: "" },
    ])
    expect(out.startsWith("[turn-check] supervisor audit of your previous work found rule violations from ~/.agents/AGENTS.md:\n")).toBe(true)
    expect(out).toContain("- Max 6 lines (#4 12 lines) Fix: shorten\n- No emoji\n")
    expect(out.endsWith("Correct these first if they still apply. Do not repeat them.")).toBe(true)
  })

  test("only a note with violations is injected", () => {
    expect(isViolationFeedback(formatFeedback([{ rule: "Max 6 lines", evidence: "#1", fix: "shorten" }]))).toBe(true)
    expect(isViolationFeedback(formatError("judge timed out after 90s"))).toBe(false)
    expect(isViolationFeedback("")).toBe(false)
    expect(isViolationFeedback("turn-check ERROR: nothing checked")).toBe(false)
  })

  test("auditor system embeds rules and instructions", () => {
    const out = auditorSystem("NO FLUFF")
    expect(out).toContain("You are a strict compliance auditor, not the coding agent.")
    expect(out).toContain("At most 5 violations")
    expect(out).toContain('{"verdict":"PASS"|"FAIL","violations":[{"rule":"short rule text","evidence":"#N quote","fix":"one sentence"}]}')
    expect(out.endsWith("RULES:\nNO FLUFF")).toBe(true)
  })
})

describe("judge event stream", () => {
  test("joins text events", () => {
    const stream = [
      { type: "step_start", part: { type: "step-start" } },
      { type: "text", part: { type: "text", text: '{"verdict":' } },
      { type: "text", part: { type: "text", text: '"PASS"}' } },
      { type: "step_finish", part: { type: "step-finish" } },
    ]
      .map((e) => JSON.stringify(e))
      .join("\n")
    expect(replyFromEvents(stream)).toBe('{"verdict":"PASS"}')
  })

  test("an error event without text raises", () => {
    expect(() => replyFromEvents(JSON.stringify({ type: "error", error: { name: "APIError" } }))).toThrow(JudgeError)
  })

  test("non-JSON output is returned raw", () => {
    expect(replyFromEvents("plain words")).toBe("plain words")
  })

  test("events without text give an empty reply", () => {
    expect(replyFromEvents(JSON.stringify({ type: "step_start" }))).toBe("")
  })
})

describe("prompt cap", () => {
  const manyUsers = (count: number, size = 1900): Msg[] => {
    const msgs: Msg[] = []
    for (let i = 0; i < count; i++) {
      msgs.push(msg("user", t(`ask${String(i).padStart(4, "0")} ` + "u".repeat(size))))
      msgs.push(msg("assistant", t(`answer${String(i).padStart(4, "0")}`)))
    }
    return msgs
  }

  test("under the cap the prompt is unchanged", () => {
    const msgs = [msg("user", t("fix it")), msg("assistant", t("done"))]
    const built = buildPrompt("RULES", msgs, 60000)
    expect(built.prompt).toBe(`${auditorSystem("RULES")}\n\nTRANSCRIPT:\n\n${renderTranscript(msgs, 60000)}`)
  })

  test("over the cap drops the oldest user messages first", () => {
    const out = buildPrompt("RULES", manyUsers(300), 60000, 100000).prompt
    expect(out.length).toBeLessThanOrEqual(100000)
    expect(out).not.toContain("ask0000")
    expect(out).toContain("ask0299")
    expect(out).toContain("answer0299")
    expect(out.startsWith(auditorSystem("RULES"))).toBe(true)
  })

  test("the default cap is 400000 characters", () => {
    expect(MAX_PROMPT_CHARS).toBe(400000)
    const out = buildPrompt("RULES", manyUsers(400), 60000).prompt
    expect(out.length).toBeLessThanOrEqual(400000)
    expect(out).toContain("ask0399")
    expect(out).not.toContain("ask0000")
  })

  test("a huge max chars cannot push the prompt over the cap", () => {
    const msgs = [msg("user", t("ask")), msg("assistant", t("z".repeat(600000)))]
    const out = buildPrompt("RULES", msgs, 10000000, 100000).prompt
    expect(out.length).toBeLessThanOrEqual(100000 + USER_MESSAGE_CAP)
    expect(out).toContain("ask")
  })

  test("nothing is dropped when it fits", () => {
    const out = buildPrompt("RULES", manyUsers(20), 60000, 400000).prompt
    expect(out).toContain("ask0000")
    expect(out).toContain("ask0019")
  })
})
